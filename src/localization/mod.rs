#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u32)]
pub enum LANGUAGE {
    Arabic = 21,
    Czech = 23,
    Danish = 14,
    Dutch = 6,
    EnglishUs = 1,
    EnglishUk = 18,
    Finnish = 12,
    FrenchCanada = 22,
    FrenchFrance = 2,
    German = 4,
    Greek = 25,
    Hungarian = 24,
    Indonesian = 29,
    Italian = 5,
    Japanese = 0,
    Korean = 9,
    Norwegian = 15,
    Polish = 16,
    PortugueseBrazil = 17,
    PortuguesePortugal = 7,
    Romanian = 26,
    Russian = 8,
    SimplifiedChinese = 11,
    SpanishLA = 20,
    SpanishSpain = 3,
    Swedish = 13,
    Thai = 27,
    TraditionalChinese = 10,
    Turkish = 19,
    Ukrainian = 30,
    Vietnamese = 28,
}

impl LANGUAGE {
    pub const ALL: &'static [LANGUAGE] = &[
        LANGUAGE::Arabic,
        LANGUAGE::Czech,
        LANGUAGE::Danish,
        LANGUAGE::Dutch,
        LANGUAGE::EnglishUs,
        LANGUAGE::EnglishUk,
        LANGUAGE::Finnish,
        LANGUAGE::FrenchCanada,
        LANGUAGE::FrenchFrance,
        LANGUAGE::German,
        LANGUAGE::Greek,
        LANGUAGE::Hungarian,
        LANGUAGE::Indonesian,
        LANGUAGE::Italian,
        LANGUAGE::Japanese,
        LANGUAGE::Korean,
        LANGUAGE::Norwegian,
        LANGUAGE::Polish,
        LANGUAGE::PortugueseBrazil,
        LANGUAGE::PortuguesePortugal,
        LANGUAGE::Romanian,
        LANGUAGE::Russian,
        LANGUAGE::SimplifiedChinese,
        LANGUAGE::SpanishLA,
        LANGUAGE::SpanishSpain,
        LANGUAGE::Swedish,
        LANGUAGE::Thai,
        LANGUAGE::TraditionalChinese,
        LANGUAGE::Turkish,
        LANGUAGE::Ukrainian,
        LANGUAGE::Vietnamese,
    ];

    // The config stores the language as a number, this turns it back into a variant
    pub fn from_id(id: u32) -> Option<LANGUAGE> {
        Self::ALL.iter().copied().find(|language| *language as u32 == id)
    }
    pub fn label(language: LANGUAGE) -> String {
        String::from(match language {
            LANGUAGE::Arabic => "Arabic",
            LANGUAGE::Czech => "Czech",
            LANGUAGE::Danish => "Danish",
            LANGUAGE::Dutch => "Dutch",
            LANGUAGE::EnglishUs => "English (US)",
            LANGUAGE::EnglishUk => "English (UK)",
            LANGUAGE::Finnish => "Finnish",
            LANGUAGE::FrenchCanada => "French (Canada)",
            LANGUAGE::FrenchFrance => "French (France)",
            LANGUAGE::German => "German",
            LANGUAGE::Greek => "Greek",
            LANGUAGE::Hungarian => "Hungarian",
            LANGUAGE::Indonesian => "Indonesian",
            LANGUAGE::Italian => "Italian",
            LANGUAGE::Japanese => "Japanese",
            LANGUAGE::Korean => "Korean",
            LANGUAGE::Norwegian => "Norwegian",
            LANGUAGE::Polish => "Polish",
            LANGUAGE::PortugueseBrazil => "Portuguese (Brazil)",
            LANGUAGE::PortuguesePortugal => "Portuguese (Portugal)",
            LANGUAGE::Romanian => "Romanian",
            LANGUAGE::Russian => "Russian",
            LANGUAGE::SimplifiedChinese => "Chinese (Simplified)",
            LANGUAGE::SpanishLA => "Spanish (Latin America)",
            LANGUAGE::SpanishSpain => "Spanish (Spain)",
            LANGUAGE::Swedish => "Swedish",
            LANGUAGE::Thai => "Thai",
            LANGUAGE::TraditionalChinese => "Chinese (Traditional)",
            LANGUAGE::Turkish => "Turkish",
            LANGUAGE::Ukrainian => "Ukrainian",
            LANGUAGE::Vietnamese => "Vietnamese",
        })
    }
}
